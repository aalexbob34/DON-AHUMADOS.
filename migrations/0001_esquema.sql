-- Esquema de la tienda Don Ahumados (Cloudflare D1)
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT NOT NULL DEFAULT '');
CREATE TABLE IF NOT EXISTS categories (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, slug TEXT NOT NULL UNIQUE,
  description TEXT DEFAULT '', image TEXT DEFAULT '', sort INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS products (
  id INTEGER PRIMARY KEY AUTOINCREMENT, slug TEXT NOT NULL UNIQUE, name TEXT NOT NULL,
  category_id INTEGER REFERENCES categories(id) ON DELETE SET NULL,
  short_desc TEXT DEFAULT '', description TEXT DEFAULT '',
  price INTEGER NOT NULL DEFAULT 0, compare_price INTEGER DEFAULT 0,
  features TEXT DEFAULT '[]', benefits TEXT DEFAULT '[]', specs TEXT DEFAULT '[]',
  usage TEXT DEFAULT '', faqs TEXT DEFAULT '[]', recommendations TEXT DEFAULT '',
  stock INTEGER NOT NULL DEFAULT 0 CHECK(stock >= 0), weight_g INTEGER DEFAULT 500,
  featured INTEGER DEFAULT 0, is_new INTEGER DEFAULT 0, active INTEGER DEFAULT 1,
  sales_count INTEGER DEFAULT 0, created_at TEXT DEFAULT (datetime('now'))
);
CREATE TABLE IF NOT EXISTS product_images (
  id INTEGER PRIMARY KEY AUTOINCREMENT, product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  url TEXT NOT NULL, sort INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS variants (
  id INTEGER PRIMARY KEY AUTOINCREMENT, product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  name TEXT NOT NULL, price INTEGER NOT NULL, stock INTEGER NOT NULL DEFAULT 0 CHECK(stock >= 0), weight_g INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
  phone TEXT DEFAULT '', address TEXT DEFAULT '', city TEXT DEFAULT '',
  pass_hash TEXT NOT NULL, salt TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'customer',
  created_at TEXT DEFAULT (datetime('now'))
);
CREATE TABLE IF NOT EXISTS sessions (
  token TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, expires INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS orders (
  id INTEGER PRIMARY KEY AUTOINCREMENT, code TEXT NOT NULL UNIQUE,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  name TEXT NOT NULL, email TEXT DEFAULT '', phone TEXT NOT NULL, address TEXT NOT NULL, city TEXT NOT NULL, notes TEXT DEFAULT '',
  subtotal INTEGER NOT NULL, shipping INTEGER NOT NULL DEFAULT 0, discount INTEGER NOT NULL DEFAULT 0, total INTEGER NOT NULL,
  coupon TEXT DEFAULT '', delivery_type TEXT NOT NULL DEFAULT 'delivery', schedule TEXT DEFAULT '', status TEXT NOT NULL DEFAULT 'pendiente',
  payment_method TEXT NOT NULL, payment_status TEXT NOT NULL DEFAULT 'pendiente',
  created_at TEXT DEFAULT (datetime('now'))
);
CREATE TABLE IF NOT EXISTS order_items (
  id INTEGER PRIMARY KEY AUTOINCREMENT, order_id INTEGER NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
  product_id INTEGER, variant_id INTEGER, name TEXT NOT NULL, variant_name TEXT DEFAULT '', note TEXT DEFAULT '',
  price INTEGER NOT NULL, qty INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS promotions (
  id INTEGER PRIMARY KEY AUTOINCREMENT, code TEXT NOT NULL UNIQUE, title TEXT DEFAULT '',
  type TEXT NOT NULL DEFAULT 'percent', value INTEGER NOT NULL, min_amount INTEGER DEFAULT 0,
  active INTEGER DEFAULT 1, starts TEXT DEFAULT '', ends TEXT DEFAULT '', show_banner INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS shipping_zones (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, cities TEXT NOT NULL DEFAULT '',
  fee INTEGER NOT NULL DEFAULT 0, free_over INTEGER DEFAULT 0, eta TEXT DEFAULT ''
);
CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER PRIMARY KEY AUTOINCREMENT, type TEXT NOT NULL, message TEXT NOT NULL,
  order_id INTEGER, read INTEGER DEFAULT 0, created_at TEXT DEFAULT (datetime('now'))
);
CREATE TABLE IF NOT EXISTS testimonials (
  id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, text TEXT NOT NULL,
  rating INTEGER DEFAULT 5, active INTEGER DEFAULT 1
);
CREATE INDEX IF NOT EXISTS idx_products_cat ON products(category_id);
CREATE INDEX IF NOT EXISTS idx_orders_user ON orders(user_id);
CREATE INDEX IF NOT EXISTS idx_items_order ON order_items(order_id);
